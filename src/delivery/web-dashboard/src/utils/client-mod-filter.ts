export function isClientOnlyMod(raw: string): boolean {
  if (!raw || typeof raw !== 'string') return false;
  const name = raw.replace(/\.[^/.]+$/, '').toLowerCase().replace(/[_+.]+/g, '-');
  return CLIENT_ONLY_PATTERNS.some((p) => p.test(name));
}
