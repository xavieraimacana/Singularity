import path from 'node:path';
import fs from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import type { CreateServerInstanceOptions, ServerInstance } from '../models/server-instance.js';
import type { ServerProperties } from '../models/server-properties.js';
import { parseProperties, serializeProperties } from './properties-parser.js';
import { findAvailablePort } from './port-allocator.js';

export class ServerLifecycleService {
  constructor(private readonly dataDir: string = path.join(process.cwd(), 'data', 'servers')) {}

  private getInstanceDir(id: string): string {
    return path.join(this.dataDir, id);
  }

  private getMetadataPath(id: string): string {
    return path.join(this.getInstanceDir(id), 'singularity-instance.json');
  }

  private getPropertiesPath(id: string): string {
    return path.join(this.getInstanceDir(id), 'server.properties');
  }

  private getEulaPath(id: string): string {
    return path.join(this.getInstanceDir(id), 'eula.txt');
  }

  async createInstance(options: CreateServerInstanceOptions): Promise<ServerInstance> {
    const id = `srv_${randomUUID().slice(0, 8)}`;
    const instanceDir = this.getInstanceDir(id);

    // 1. Determine Port
    const port = options.port ?? (await findAvailablePort(25565));

    // 2. Create Instance Directories
    await fs.mkdir(instanceDir, { recursive: true });
    await fs.mkdir(path.join(instanceDir, 'mods'), { recursive: true });
    await fs.mkdir(path.join(instanceDir, 'plugins'), { recursive: true });
    await fs.mkdir(path.join(instanceDir, 'datapacks'), { recursive: true });
    await fs.mkdir(path.join(instanceDir, 'backups'), { recursive: true });

    // 3. Write eula.txt (auto-accepted by Singularity)
    await fs.writeFile(
      this.getEulaPath(id),
      '#By changing the setting below to TRUE you are indicating your agreement to the Mojang EULA (https://aka.ms/MinecraftEULA).\neula=true\n',
      'utf8'
    );

    // 4. Write default server.properties
    const initialProps: ServerProperties = {
      headers: ['#Minecraft server properties', `#Generated by Singularity for ${options.name}`],
      properties: {
        'server-port': port,
        'gamemode': 'survival',
        'difficulty': 'easy',
        'pvp': true,
        'max-players': 20,
        'online-mode': true,
        'enable-command-block': true,
        'motd': options.name,
        'view-distance': 10
      }
    };
    await fs.writeFile(this.getPropertiesPath(id), serializeProperties(initialProps), 'utf8');

    // 5. Construct Instance Metadata
    const now = new Date().toISOString();
    const instance: ServerInstance = {
      id,
      name: options.name,
      loader: options.loader,
      gameVersion: options.gameVersion,
      loaderVersion: options.loaderVersion,
      memoryMb: options.memoryMb ?? 4096,
      port,
      javaPath: options.javaPath,
      jvmArgs: options.jvmArgs ?? [],
      autoRestart: options.autoRestart ?? false,
      status: 'offline',
      eulaAccepted: true,
      createdAt: now,
      updatedAt: now
    };

    // 6. Write Metadata
    await fs.writeFile(this.getMetadataPath(id), JSON.stringify(instance, null, 2), 'utf8');

    return instance;
  }

  async getInstance(id: string): Promise<ServerInstance | null> {
    try {
      const raw = await fs.readFile(this.getMetadataPath(id), 'utf8');
      return JSON.parse(raw) as ServerInstance;
    } catch {
      return null;
    }
  }

  async listInstances(): Promise<ServerInstance[]> {
    try {
      await fs.mkdir(this.dataDir, { recursive: true });
      const entries = await fs.readdir(this.dataDir, { withFileTypes: true });
      const instances: ServerInstance[] = [];

      for (const entry of entries) {
        if (entry.isDirectory()) {
          const inst = await this.getInstance(entry.name);
          if (inst) {
            instances.push(inst);
          }
        }
      }

      return instances.sort(
        (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
      );
    } catch {
      return [];
    }
  }

  async updateInstance(id: string, updates: Partial<ServerInstance>): Promise<ServerInstance> {
    const current = await this.getInstance(id);
    if (!current) {
      throw new Error(`Instancia no encontrada: ${id}`);
    }

    const updated: ServerInstance = {
      ...current,
      ...updates,
      id: current.id, // Immutable
      updatedAt: new Date().toISOString()
    };

    await fs.writeFile(this.getMetadataPath(id), JSON.stringify(updated, null, 2), 'utf8');
    return updated;
  }

  async deleteInstance(id: string): Promise<void> {
    const instanceDir = this.getInstanceDir(id);
    await fs.rm(instanceDir, { recursive: true, force: true });
  }

  async acceptEula(id: string): Promise<void> {
    await fs.writeFile(
      this.getEulaPath(id),
      '#By changing the setting below to TRUE you are indicating your agreement to the Mojang EULA (https://aka.ms/MinecraftEULA).\neula=true\n',
      'utf8'
    );
    await this.updateInstance(id, { eulaAccepted: true });
  }

  async getProperties(id: string): Promise<ServerProperties> {
    const content = await fs.readFile(this.getPropertiesPath(id), 'utf8');
    return parseProperties(content);
  }

  async saveProperties(id: string, properties: ServerProperties): Promise<void> {
    const content = serializeProperties(properties);
    await fs.writeFile(this.getPropertiesPath(id), content, 'utf8');

    // Sync port if changed in properties
    const portVal = properties.properties['server-port'];
    if (typeof portVal === 'number') {
      await this.updateInstance(id, { port: portVal });
    }
  }
}
